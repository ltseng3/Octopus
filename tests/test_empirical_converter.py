def test_import_two_vehicle_aligned_and_grounded(tmp_path):
    rep = import_box_manifest(FIX/'frames.jsonl', tmp_path)
    assert rep.source_frames == 2
    assert rep.valid_events == 6
    assert rep.positive_events == 4
    assert rep.negative_events == 2
    trace = [json.loads(l) for l in rep.trace_path.read_text().splitlines()]
    assert [r['truth'] for r in trace[:3]] == [0, 1, 1]
    assert [r['arrival_slot'] for r in trace] == [0,0,0,1,1,1]
    assert len({r['frame_id'] for r in trace})==2
    assert all('frame_id' in r for r in trace)
    assert trace[1]['candidates'] == {
        'edge:veh_a': 1, 'edge:veh_b': 0,
        'local:veh_a': 1, 'local:veh_b': 0,
    }
    cfg = ExperimentConfig.load(tmp_path/'scenario.json')
    assert cfg.data['world']['backend'] == 'trace'
    sim = run_simulation(cfg, detailed_events=False)
    assert len(sim.scores) == 6
    assert sim.summary['edge_inference_executions'] == 4  # one per agent per physical frame
    assert [s['released_ms'] for s in sim.scores] == [0,0,0,250,250,250]
    # Inferred errors are from the constructed predictor, not Monte Carlo.
    assert sim.scores[1]['wrong']['veh_a'] is False
    assert sim.scores[1]['wrong']['veh_b'] is True
    manifest = json.loads(rep.report_path.read_text())
    assert manifest['source_frames'] == 2
    assert len(manifest['input_file_hashes']) == 6
    assert manifest['data_status'] == 'recorded predictions, not generated by this importer'


