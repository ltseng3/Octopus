def test_open_carla_rpy_transform():
    xyz = _to_world((3,0,0), (10,20,0,0,90,0))
    assert xyz == pytest.approx((10,23,0), abs=1e-7)
    xyz = _to_world((1,2,3), (10,-2,5,0,0,0))
    assert xyz == pytest.approx((11,0,8))
    assert _to_world((0,0,0), (1,2,3,12,49,19)) == pytest.approx((1,2,3))


def test_corner_3d_centroids(tmp_path):
    bbox = [[[x,y,z] for x in (1,3) for y in (-2,2) for z in (0,2)]]
    assert _as_xy(bbox, tmp_path) == [(2,0,1)]
    assert _as_xy([], tmp_path) == []
    with pytest.raises(ImportFailure):
        _as_xy([[[1,2],[2,3],[4,5]]], tmp_path)
    with pytest.raises(ImportFailure):
        _as_xy([['nan',0,0]], tmp_path)


def test_reject_missing_files(tmp_path):
    frame = json.loads((FIX/'frames.jsonl').read_text().splitlines()[0])
